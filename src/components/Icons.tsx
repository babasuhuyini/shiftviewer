export function ToneIcon({ tone, size = 18 }: { tone: Tone; size?: number }) {
  switch (tone) {
    case 'morning':
      return <SunIcon size={size} />;
    case 'afternoon':
      return <SunsetIcon size={size} />;
    case 'night':
      return <MoonIcon size={size} />;
    case 'shift':
      return <ClockIcon size={size} />;
    case 'off':
      return <RestIcon size={size} />;
    case 'leave':
      return <SuitcaseIcon size={size} />;
    case 'unassigned':
      return <DashIcon size={size} />;
    default:
      return <QuestionIcon size={size} />;
  }
}
